function appendNavigationItem(presetKey, sectionName, item) {
  const section = navigationPresets[presetKey]?.find((entry) => entry.section === sectionName);

  if (!section) {
    return;
  }

  if (section.items.some((entry) => entry.path === item.path)) {
    return;
  }

  section.items.push(item);
}

